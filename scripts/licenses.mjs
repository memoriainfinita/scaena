// Writes THIRD-PARTY-NOTICES.md from what is installed: `node scripts/licenses.mjs`.
// Only production dependencies (what ships to the browser); development tools are not distributed.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const raw = execSync('pnpm licenses list --json --prod', { encoding: 'utf8' });
const byLicense = JSON.parse(raw);
const rows = Object.entries(byLicense).flatMap(([license, pkgs]) => pkgs.map((p) => ({ name: p.name, version: p.versions.join(', '), license, homepage: p.homepage ?? '' })));
rows.sort((a, b) => a.name.localeCompare(b.name));

// GPL-3.0-only can include code under these (see https://www.gnu.org/licenses/license-list.html).
const COMPATIBLE = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'Unlicense', 'CC0-1.0', 'Zlib', '(MIT AND Zlib)', 'OFL-1.1']);
const odd = rows.filter((r) => !COMPATIBLE.has(r.license));

const own = JSON.parse(readFileSync('package.json', 'utf8'));
const lines = [
  '# Third-party notices',
  '',
  `scaena ${own.version} is released under the GNU General Public License, version 3 only (see LICENSE). It ships the software below, each under its own license. The list is what pnpm installs as production dependencies, so it can include packages the bundler does not send to the browser (for example the native, Node-only module that pdf.js lists as optional). This file is generated by \`node scripts/licenses.mjs\`; do not edit it by hand.`,
  '',
  '## Code',
  '',
  '| Package | Version | License |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.homepage ? `[${r.name}](${r.homepage})` : r.name} | ${r.version} | ${r.license} |`),
  '',
  '## Fonts',
  '',
  '- **Inter** (Copyright 2016 The Inter Project Authors) and **JetBrains Mono** (Copyright 2020 The JetBrains Mono Project Authors), SIL Open Font License 1.1. They are bundled for the screen as woff2 files by `@fontsource-variable/*` and embedded in generated PDFs as subsets (Latin Extended; Greek, Cyrillic and combining marks are added only for documents that use them, from `public/typst/fonts/wide/`). The subsets are built by `scripts/fonts/subset-pdf-fonts.sh`. The license texts are in `public/typst/fonts/LICENSES.txt`.',
  '',
  '## Data',
  '',
  '- **Open Fixture Library** (Copyright (c) 2017 Florian & Felix Edelmann), MIT license: weight, power and beam angle of the lighting fixtures listed under the Open Fixture Library group in the model list. Built by `scripts/import-ofl.mjs` into `src/library/ofl-data.json`; the license text is in `third_party/open-fixture-library-LICENSE`. Source: https://github.com/OpenLightingProject/open-fixture-library',
  '',
  '## Typst compiler',
  '',
  '- The PDF is compiled in the browser by the Typst compiler (Apache-2.0) as built into `@myriaddreamin/typst-ts-web-compiler` (Apache-2.0). The WebAssembly file also contains the Rust libraries that Typst depends on; their licenses are listed in the Typst and typst.ts repositories and are not enumerated here.',
  '',
  '## Compatibility check',
  '',
  odd.length === 0 ? 'Every production dependency above is under a license compatible with GPL-3.0-only.' : `Not in the compatible list and to be reviewed: ${odd.map((r) => `${r.name} (${r.license})`).join(', ')}.`,
  '',
];
writeFileSync('THIRD-PARTY-NOTICES.md', lines.join('\n'));
console.log(`${rows.length} packages; ${odd.length} to review`);
if (odd.length) console.log(odd);
