"""Writes docs/design/icons-catalog.md: every library item with its icon, grouped by category.
usage: python scripts/symbols/build-catalog.py   (after build-items.py)"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
icon_of = dict(re.findall(r"'([^']+)': '([^']+)'", (ROOT / 'src/library/icon-map.ts').read_text(encoding='utf8')))
BS = chr(92)
Q = "((?:[^'" + BS + BS + "]|" + BS + BS + ".)*)"
pat = re.compile("id: '([^']+)', category: '([^']+)'.*?name: b" + BS + "('" + Q + "', '" + Q + "'" + BS + ")")
rows = {}
for f in ('items.ts', 'items-more.ts', 'items-icons.ts'):
    for line in (ROOT / 'src/library' / f).read_text(encoding='utf8').split(chr(10)):
        m = pat.search(line)
        if m:
            i, cat, es, en = m.groups()
            rows.setdefault(cat, []).append((i, es.replace(chr(92) + "'", "'"), en.replace(chr(92) + "'", "'"), icon_of.get(i, '')))
total = sum(len(v) for v in rows.values())
withicon = sum(1 for v in rows.values() for r in v if r[3])
out = ['# Icon catalogue', '', f'Generated by `scripts/symbols/build-catalog.py`. {total} library items, {withicon} with an icon. Use it to see what is missing before asking for new sheets;',
       'an empty icon column means the item still draws its old top-view symbol. Icon keys are `sheet-number`, see `assets/symbol-manifest.json`.', '']
for cat in sorted(rows):
    out += [f'## {cat} ({len(rows[cat])})', '', '| Id | Español | English | Icon |', '|---|---|---|---|']
    out += [f'| `{i}` | {es} | {en} | {k} |' for i, es, en, k in sorted(rows[cat])]
    out.append('')
(ROOT / 'docs/design/icons-catalog.md').write_text(chr(10).join(out), encoding='utf8')
print(total, withicon, len(rows))
