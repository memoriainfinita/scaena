"""Writes src/library/icon-map.ts: library item id -> icon key.
Existing items map by the proposed id of the sheet lists, or by scripts/symbols/item-map.json where it was redone.
usage: python scripts/symbols/build-map.py   (after build-manifest.py)"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
manifest = json.load(open(ROOT / 'assets/symbol-manifest.json', encoding='utf8'))
manual = json.load(open(ROOT / 'scripts/symbols/item-map.json', encoding='utf8'))['existing']
src = (ROOT / 'src/library/items.ts').read_text(encoding='utf8') + (ROOT / 'src/library/items-more.ts').read_text(encoding='utf8')
existing = re.findall(r"id: '([a-z0-9.@-]+)'", src)
keys = {m['key'] for m in manifest}
assert all(v in keys for v in manual.values()), [v for v in manual.values() if v not in keys]
out = {}
for m in manifest:
    if m['pid'] in existing and m['pid'] not in out:
        out[m['pid']] = m['key']
out.update(manual)
lines = ['// Generated by scripts/symbols/build-map.py. Do not edit by hand.', '// Library item id -> icon key (see icons/<sheet>.json).', 'export const ICON_OF: Record<string, string> = {']
for k in sorted(out):
    lines.append(f"  '{k}': '{out[k]}',")
lines.append('};')
(ROOT / 'src/library/icon-map.ts').write_text('\n'.join(lines) + '\n', encoding='utf8')
print(len(out), 'items mapped;', 'existing without icon:', sorted(i for i in existing if i not in out))
